-- 5. find the customers who have placed orders in cities where sellers are located and 
-- whose total spending is greater than 25000. display the customer name and total spending.
select c.first_name,c.last_name, sum(o.total_amount) as total_spending 
from customers c join orders o on c.customer_id = o.customer_id
where o.city in ( select city from sellers)
group by c.customer_id, c.first_name,c.last_name
having sum(o.total_amount) > 25000;
-- ------------------------------------------------------------------------------------------------------------------
-- 6. Which products have generated more revenue than the average revenue generated by all products?
with product_revenue as (select p.product_id, p.product_name,sum(o.total_amount) as total_revenue
from products p join orders o on p.product_id = o.product_id
group by p.product_id, p.product_name)
select * from product_revenue where total_revenue > (select avg(total_revenue)from product_revenue);
