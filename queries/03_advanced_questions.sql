--  1.create a view called product_sales_summary that stores each product's total quantity sold and total revenue.
create view product_sales_summary as
select p.product_id,p.product_name,sum(o.quantity) as total_quantity,sum(o.total_amount) as total_revenue 
from products p join orders o on p.product_id = o.product_id
group by p.product_id,p.product_name
order by p.product_id;

select * from product_sales_summary;

-- ------------------------------------------------------------------------------------------------------------------

-- 2. Display top 3 products whose revenue is above the average product revenue
select * from product_sales_summary 
where total_revenue > ( select avg(total_revenue) from product_sales_summary)
order by total_revenue desc limit 3;

-- ------------------------------------------------------------------------------------------------------------------

-- 3. Find the products whose unit_price is greater than the average product price.
select product_name, unit_price from products
where unit_price > (select avg(unit_price) from products);

-- ------------------------------------------------------------------------------------------------------------------

-- 4. Find the products that belong to the Electronics or Books categories using a subquery.
select * from products where category in ( select category from products 
where category in ('electronics', 'books'));

