--  7. Find the top 3 customers based on their total spending
select customer_id, total_spending
from (select customer_id,sum(total_amount) as total_spending,
dense_rank() over(order by sum(total_amount) desc) as rnk
from orders group by customer_id) as t
where rnk <= 3;
-- ------------------------------------------------------------------------------------------------------------------

-- 8. find the ranking of sellers based on the total number of orders received for their products
select seller_id, seller_name, total_orders, dense_rank() over(order by total_orders desc) as seller_rank
from (select s.seller_id, s.seller_name,count(o.order_id) as total_orders 
from sellers s join products p on s.seller_id = p.seller_id
join orders o on p.product_id = o.product_id
group by s.seller_id, s.seller_name) as t;
-- ------------------------------------------------------------------------------------------------------------------
-- 9. Find the second-highest spending customer.
select customer_id,first_name,last_name,highest_spend from
(select c.customer_id, c.first_name,c.last_name,sum(o.total_amount) as highest_spend,
dense_rank() over (order by sum(total_amount) desc) as spending_rank
from customers c join orders o on c.customer_id = o.customer_id 
group by c.customer_id, c.first_name,c.last_name) as second_highest 
where spending_rank=2;

